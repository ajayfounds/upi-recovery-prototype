// Builds the static prototype site from the Design Canvas screen sources.
// node tools/build.js [sourceDir] [outDir]  — defaults: source/ -> site/
const fs = require('fs');
const path = require('path');

const SRC = path.resolve(process.argv[2] || path.join(__dirname, '..', 'source'));
const OUT = path.resolve(process.argv[3] || path.join(__dirname, '..', 'site'));
const HERE = __dirname;

const SCREENS = ['Checking', 'Status', 'Explainer', 'Waiting', 'Notification', 'Escalation',
  'Handoff', 'Success', 'Reassurance', 'Duplicate', 'Refunded'];

const THEMES = [
  { slug: 'daylight', prefix: 'Day', css: 'day.css', label: 'Daylight', other: 'midnight', otherLabel: 'Midnight', bg: '#EBEDF1', ink: '#0B1220', sub: '#4A5363', chip: '#FFFFFF', line: 'rgba(11,18,32,.08)', scheme: 'light' },
  { slug: 'midnight', prefix: 'Night', css: 'night.css', label: 'Midnight', other: 'daylight', otherLabel: 'Daylight', bg: '#05070A', ink: '#F5F7FA', sub: '#A9B1BE', chip: '#111419', line: 'rgba(255,255,255,.08)', scheme: 'dark' },
];

function parse(file) {
  const src = fs.readFileSync(path.join(SRC, file), 'utf8');
  const x = src.match(/<x-dc>([\s\S]*?)<\/x-dc>/);
  if (!x) throw new Error('no <x-dc> in ' + file);
  const html = x[1].replace(/<helmet>[\s\S]*?<\/helmet>/g, '').trim();
  const s = src.match(/<script[^>]*data-dc-script[^>]*>([\s\S]*?)<\/script>/);
  const code = s ? s[1].trim() : 'class Component extends DCLogic {}';
  return { html, code };
}

function screensBundle(theme) {
  const names = SCREENS.map(n => theme.prefix + n).concat([theme.prefix + 'Main']);
  let out = '/* generated by build.js — do not edit */\n';
  for (const name of names) {
    const { html, code } = parse(name + '.dc.html');
    out += `DC.register(${JSON.stringify(name)}, ${JSON.stringify(html)}, (function(){\n${code}\nreturn Component;\n})());\n`;
  }
  return out;
}

